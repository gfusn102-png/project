function renderSlide(index) {
  const s = slidesData[index];
  const slideClass = s.type ? `slide-${s.type}` : '';
  
  app.innerHTML = `
    <div class="slide-card ${slideClass}" id="slideEl">
      <h1 class="slide-title" id="slideTitle">${s.title}</h1>
      <p class="slide-content" id="slideContent">${s.content}</p>
    </div>
  `;
  
  requestAnimationFrame(() => {
    const slideEl = document.getElementById('slideEl');
    const titleEl = document.getElementById('slideTitle');
    const contentEl = document.getElementById('slideContent');
    
    slideEl.classList.add('visible');
    
    // انیمیشن عنوان
    if (titleEl) {
      titleEl.style.opacity = '0';
      titleEl.animate([
        { opacity: 0, transform: 'translateY(-40px) rotateX(20deg)', filter: 'blur(10px)' },
        { opacity: 1, transform: 'translateY(0) rotateX(0deg)', filter: 'blur(0px)' }
      ], {
        duration: 1000,
        easing: 'cubic-bezier(0.25, 0.46, 0.45, 0.94)',
        fill: 'forwards',
        delay: 200
      });
    }
    
    // انیمیشن متن
    if (contentEl) {
      contentEl.style.opacity = '0';
      contentEl.animate([
        { opacity: 0, transform: 'translateY(50px)', filter: 'blur(8px)' },
        { opacity: 1, transform: 'translateY(0)', filter: 'blur(0px)' }
      ], {
        duration: 1200,
        easing: 'cubic-bezier(0.25, 0.46, 0.45, 0.94)',
        fill: 'forwards',
        delay: 600
      });
    }
    
    // Glow برای آیات
    if (s.type === 'quran' && contentEl) {
      contentEl.animate([
        { textShadow: '0 0 10px rgba(212,175,55,0.2)' },
        { textShadow: '0 0 30px rgba(212,175,55,0.8), 0 0 60px rgba(212,175,55,0.5)' },
        { textShadow: '0 0 10px rgba(212,175,55,0.2)' }
      ], {
        duration: 3500,
        iterations: Infinity,
        easing: 'ease-in-out'
      });
    }
    
    // درخشش عنوان
    if (s.type === 'main' && titleEl) {
      titleEl.animate([
        { boxShadow: '0 0 0 rgba(212,175,55,0)' },
        { boxShadow: '0 0 30px rgba(212,175,55,0.6)' },
        { boxShadow: '0 0 0 rgba(212,175,55,0)' }
      ], {
        duration: 3000,
        iterations: Infinity,
        easing: 'ease-in-out',
        delay: 1500
      });
    }
    
    // جلد
    if (s.type === 'cover' && titleEl) {
      titleEl.animate([
        { transform: 'scale(0.85) translateY(-40px)', opacity: 0 },
        { transform: 'scale(1.08) translateY(0)', opacity: 1 },
        { transform: 'scale(1) translateY(0)', opacity: 1 }
      ], {
        duration: 1500,
        easing: 'cubic-bezier(0.34, 1.56, 0.64, 1)',
        fill: 'forwards'
      });
    }
    
    // پایانی
    if (s.type === 'final' && contentEl) {
      contentEl.animate([
        { letterSpacing: '0px', opacity: 0 },
        { letterSpacing: '3px', opacity: 1 },
        { letterSpacing: '0px', opacity: 1 }
      ], {
        duration: 2200,
        easing: 'ease-out',
        fill: 'forwards',
        delay: 500
      });
    }
  });
  
  currentSlideEl.textContent = toPersian(index + 1);
  progressFill.style.width = ((index + 1) / slidesData.length * 100) + '%';
  prevBtn.disabled = index === 0;
  nextBtn.disabled = index === slidesData.length - 1;
  
  progressFill.animate([
    { boxShadow: '0 0 5px rgba(212,175,55,0.5)' },
    { boxShadow: '0 0 25px rgba(212,175,55,1), 0 0 50px rgba(212,175,55,0.7)' },
    { boxShadow: '0 0 5px rgba(212,175,55,0.5)' }
  ], {
    duration: 1500,
    easing: 'ease-out'
  });
}

