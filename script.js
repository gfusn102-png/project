// خط طلایی (کشیدن انگشت/موس)
// ==========================================
let isDrawing = false;
let startX = 0, startY = 0;
let currentLine = null;

function startLine(x, y) {
  isDrawing = true;
  startX = x;
  startY = y;
  currentLine = document.createElement('div');
  currentLine.className = 'draw-line';
  currentLine.style.left = x + 'px';
  currentLine.style.top = y + 'px';
  currentLine.style.width = '0px';
  currentLine.style.opacity = '1';
  document.body.appendChild(currentLine);
}

function moveLine(x, y) {
  if (!isDrawing || !currentLine) return;
  const dx = x - startX;
  const dy = y - startY;
  const distance = Math.sqrt(dx * dx + dy * dy);
  const angle = Math.atan2(dy, dx) * (180 / Math.PI);
  currentLine.style.width = distance + 'px';
  currentLine.style.transform = `rotate(${angle}deg)`;
  currentLine.style.transformOrigin = 'left center';
}

function endLine() {
  if (currentLine) {
    currentLine.style.opacity = '0';
    currentLine.style.transition = 'opacity 0.8s ease';
    const lineToRemove = currentLine;
    setTimeout(() => lineToRemove.remove(), 800);
  }
  isDrawing = false;
  currentLine = null;
}

// تاچ
